//! `cargo goose`: Goose bindings for a Rust crate that uses
//! `#[goose::export]`, and the commands around them (build, run, test, new,
//! package). The library half is what `goose_build` and the tests use.

pub mod gen;
pub mod meta;
pub mod package;
pub mod scaffold;
pub mod sidecar;
pub mod toolchain;
pub mod verify;
mod zero_copy;

use std::path::{Path, PathBuf};

/// What `bindings` produced.
pub struct Bindings {
    pub library: meta::Library,
    pub module: String,
    /// The shared library the records were read from.
    pub cdylib: PathBuf,
    pub crate_info: toolchain::CrateInfo,
}

/// Builds the crate (unless `lib` names a built library), reads its records
/// and writes the Goose module's text.
pub fn bindings(
    manifest: Option<&Path>,
    lib: Option<&Path>,
    build: &toolchain::BuildOpts,
    opts: &gen::Options,
) -> Result<Bindings, String> {
    let ci = toolchain::crate_info(manifest)?;
    if !ci.crate_types.iter().any(|t| t == "cdylib") && lib.is_none() {
        return Err(format!(
            "{}: the library needs crate-type = [\"cdylib\"] (and \"staticlib\" for linking it into a program)",
            ci.manifest.display()
        ));
    }
    let cdylib = match lib {
        Some(l) => l.to_path_buf(),
        None => {
            toolchain::cargo_build(&ci, build)?;
            toolchain::cdylib_path(&ci, build)
        }
    };
    let library = meta::read_library(&cdylib)?;
    let mut opts = opts.clone();
    if let gen::Link::Dynamic(l) = &mut opts.link {
        if l.is_empty() {
            *l = ci.lib_name.clone();
        }
    }
    let module = gen::generate(&library, &opts)?;
    Ok(Bindings { library, module, cdylib, crate_info: ci })
}

/// Writes a generated module to `path`, refusing to replace a file that
/// cargo goose did not write (a program named like the namespace, say).
pub fn write_module(path: &Path, text: &str) -> Result<bool, String> {
    if let Ok(old) = std::fs::read_to_string(path) {
        if !old.starts_with("// Generated by cargo goose") {
            return Err(format!(
                "{} exists and is not a module cargo goose wrote: rename it, or write the module elsewhere with -o",
                path.display()
            ));
        }
    }
    write_if_changed(path, text)
}

/// Writes `text` to `path` unless it already holds it; whether it wrote.
pub fn write_if_changed(path: &Path, text: &str) -> Result<bool, String> {
    if std::fs::read_to_string(path).map(|t| t == text).unwrap_or(false) {
        return Ok(false);
    }
    if let Some(d) = path.parent() {
        if !d.as_os_str().is_empty() {
            std::fs::create_dir_all(d).map_err(|e| format!("cannot create {}: {e}", d.display()))?;
        }
    }
    std::fs::write(path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    Ok(true)
}
