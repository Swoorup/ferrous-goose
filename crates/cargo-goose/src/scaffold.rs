//! `cargo goose new`: a crate with the attributes in place, a Goose example
//! beside it and a Goose test `cargo goose test` runs.

use std::path::{Path, PathBuf};

fn write_new(path: &Path, text: &str, created: &mut Vec<PathBuf>) -> Result<(), String> {
    if path.exists() {
        return Err(format!("{} exists; cargo goose new writes only new files", path.display()));
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d).map_err(|e| format!("cannot create {}: {e}", d.display()))?;
    }
    std::fs::write(path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    created.push(path.to_path_buf());
    Ok(())
}

/// Creates the crate at `dir`. `goose_crate` points the dependency at a
/// checkout of the `goose` crate rather than a registry version.
pub fn new_crate(dir: &Path, namespace: Option<&str>, goose_crate: Option<&Path>) -> Result<Vec<PathBuf>, String> {
    let name = dir
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or("the crate's directory needs a name")?
        .to_string();
    let ns = namespace.map(String::from).unwrap_or_else(|| {
        let n = name.replace('-', "_");
        n.strip_prefix("goose_").unwrap_or(&n).to_string()
    });
    let lib = name.replace('-', "_");
    let dep = match goose_crate {
        Some(p) => {
            let abs = std::fs::canonicalize(p).map_err(|e| format!("{}: {e}", p.display()))?;
            format!("goose = {{ package = \"ferrous-goose\", path = \"{}\" }}", abs.display())
        }
        None => "goose = { package = \"ferrous-goose\", version = \"0.1\" }".to_string(),
    };
    let mut created = Vec::new();
    write_new(
        &dir.join("Cargo.toml"),
        &format!(
            r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2021"

[lib]
# cdylib: what goose run opens; staticlib: what a cargo_crate build links.
crate-type = ["cdylib", "staticlib", "rlib"]

[dependencies]
{dep}

[package.metadata.goose]
namespace = "{ns}"       # the Goose module the exports land in

[workspace]
"#
        ),
        &mut created,
    )?;
    write_new(
        &dir.join("src/lib.rs"),
        r#"//! Rust for Goose programs: each #[goose::export] function is callable from
//! Goose through the module `cargo goose bindings` writes.

use goose::GooseBuf;

/// A counter living on the Rust side. Goose holds a handle: release it.
#[goose::handle]
pub struct Counter {
    total: i64,
}

/// A new counter starting at `start`.
#[goose::export]
pub fn counter(start: i64) -> Counter {
    Counter { total: start }
}

/// Adds every value of the slice; the new total.
#[goose::export]
pub fn add_all(c: &mut Counter, values: &[i64]) -> i64 {
    c.total += values.iter().sum::<i64>();
    c.total
}

/// The total, as text, appended to `out`.
#[goose::export]
pub fn describe(c: &Counter, out: &mut GooseBuf) {
    use std::fmt::Write;
    let _ = write!(out, "total = {}", c.total);
}

/// The first word of the text: a view of it, not a copy.
#[goose::export]
pub fn first_word(text: &str) -> Option<&str> {
    text.split_whitespace().next()
}
"#,
        &mut created,
    )?;
    write_new(
        &dir.join("goose/main.goose"),
        &format!(
            r#"// cargo goose run goose/main.goose
import {ns};

fn main() {{
    let c = {ns}::counter(10);
    print("total ", {ns}::add_all(c, [1, 2, 3]));
    var text: u8[>..] = [];
    {ns}::describe(c, text);
    print(text);
    let w, ok = {ns}::first_word("hello from goose");
    if ok {{ print("first word: ", w); }}
    {ns}::release(c);
}}
"#
        ),
        &mut created,
    )?;
    write_new(
        &dir.join("goose-tests/counting.goose"),
        &format!(
            r#"// cargo goose test runs every program here; one that exits with 0 and
// prints what counting.expected holds passes.
import {ns};

fn main() {{
    let c = {ns}::counter(0);
    assert({ns}::add_all(c, [4, 5]) == 9);
    {ns}::release(c);
    assert({ns}::live_count() == 0);
    print("counted");
}}
"#
        ),
        &mut created,
    )?;
    write_new(&dir.join("goose-tests/counting.expected"), "counted\n", &mut created)?;
    write_new(
        &dir.join(".gitignore"),
        &format!("/target\n# Generated by cargo goose\n/goose/{ns}.goose\n/goose-tests/{ns}.goose\n"),
        &mut created,
    )?;
    write_new(
        &dir.join("README.md"),
        &format!(
            "# {name}\n\nRust for Goose programs, through Ferrous Goose.\n\n\
             ```sh\ncargo goose run goose/main.goose   # build, write goose/{ns}.goose, run\n\
             cargo goose test                   # the programs in goose-tests/\n\
             cargo goose bindings -o {ns}.goose # just the module\n```\n\n\
             The library is `{lib}`; a Goose program imports `{ns}`.\n"
        ),
        &mut created,
    )?;
    Ok(created)
}
