//! The Rust module for a Goose program's interface: a mirror of each struct
//! and enum the exports reach, the C declarations, and one safe function per
//! export fn taking the `goose::Runtime` token.

use crate::iface::*;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern", "false", "fn",
    "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self",
    "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become",
    "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn ident(n: &str) -> String {
    if RUST_KEYWORDS.contains(&n) {
        format!("r#{n}")
    } else {
        n.to_string()
    }
}

fn snake(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 && !out.ends_with('_') {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// A Goose doc comment (the `//` lines above a declaration) as text.
fn doc_lines(doc: &str) -> Vec<String> {
    doc.lines()
        .map(|l| {
            let l = l.trim_start();
            let l = l.strip_prefix("//").unwrap_or(l);
            l.strip_prefix(' ').unwrap_or(l).to_string()
        })
        .collect()
}

pub struct Gen<'a> {
    iface: &'a Interface,
    program: &'a str,
    /// Goose qualified name -> Rust type name.
    names: BTreeMap<String, String>,
    out: String,
}

pub fn generate(iface: &Interface, program: &str) -> Result<String, String> {
    let mut names = BTreeMap::new();
    let mut leaves: BTreeMap<String, usize> = BTreeMap::new();
    for s in &iface.structs {
        *leaves.entry(s.name.clone()).or_default() += 1;
    }
    for e in &iface.enums {
        *leaves.entry(e.name.clone()).or_default() += 1;
    }
    let mut taken = BTreeSet::new();
    let mut add = |q: &str, leaf: &str| {
        let n = if leaves.get(leaf).copied().unwrap_or(0) > 1 { q.replace("::", "_") } else { leaf.to_string() };
        taken.insert(n.clone());
        names.insert(q.to_string(), n);
    };
    for s in &iface.structs {
        add(&s.qname, &s.name);
    }
    for e in &iface.enums {
        add(&e.qname, &e.name);
    }
    let mut g = Gen { iface, program, names, out: String::new() };
    g.run()?;
    Ok(g.out)
}

impl Gen<'_> {
    fn tname(&self, q: &str) -> String {
        self.names.get(q).cloned().unwrap_or_else(|| q.replace("::", "_"))
    }

    /// A Goose type as a Rust field or value type.
    fn rty(&self, t: &GTy) -> Result<String, String> {
        Ok(match t {
            GTy::Prim(p) => p.clone(),
            GTy::Struct(q) | GTy::Enum(q) => self.tname(q),
            GTy::Array { elem, len } => format!("[{}; {len}]", self.rty(elem)?),
            other => return Err(format!("{other:?} has no Rust value type here")),
        })
    }

    /// The type as the C declaration takes or returns it by value.
    fn cty(&self, t: &GTy) -> Result<String, String> {
        Ok(match t {
            GTy::Prim(p) if p == "bool" => "u8".to_string(),
            GTy::Prim(p) => p.clone(),
            GTy::Struct(q) | GTy::Enum(q) => self.tname(q),
            GTy::Array { .. } => return Err("a fixed array by value cannot cross to Rust; wrap it in a struct".into()),
            other => return Err(format!("{other:?} cannot cross by value")),
        })
    }

    fn fields(&self, fields: &[Field], size: usize, out: &mut Vec<(String, String, usize)>) -> Result<(), String> {
        let mut pad = 0;
        let mut cursor = 0;
        for f in fields {
            match f {
                Field::Pad { pad: n, offset } => {
                    if *n > 0 {
                        out.push((format!("_pad{pad}"), format!("[u8; {n}]"), *offset));
                        pad += 1;
                    }
                    cursor = offset + n;
                }
                Field::Named { name, ty, offset, size } => {
                    out.push((ident(name), self.rty(ty)?, *offset));
                    cursor = offset + size;
                }
            }
        }
        if size > cursor {
            out.push((format!("_pad{pad}"), format!("[u8; {}]", size - cursor), cursor));
        }
        Ok(())
    }

    fn run(&mut self) -> Result<(), String> {
        let iface = self.iface;
        let mut o = String::new();
        let _ = writeln!(o, "// Generated by goose_build from the Goose program {}. Do not edit.", self.program);
        let _ = writeln!(o, "#[allow(unused_imports)]\nuse ::goose::{{GooseSlice, Runtime}};\n");
        for s in &iface.structs {
            let name = self.tname(&s.qname);
            let mut fs = Vec::new();
            self.fields(&s.fields, s.size, &mut fs)?;
            for l in doc_lines(&s.doc) {
                let _ = writeln!(o, "/// {l}");
            }
            let _ = writeln!(o, "/// Goose's `{}`, laid out as Goose lays it out.", s.qname);
            if s.align > 1 {
                let _ = writeln!(o, "#[repr(C, align({}))]", s.align);
            } else {
                let _ = writeln!(o, "#[repr(C, packed)]");
            }
            let _ = writeln!(o, "#[derive(Clone, Copy, Debug, Default, PartialEq)]");
            let _ = writeln!(o, "pub struct {name} {{");
            for (n, t, _) in &fs {
                let _ = writeln!(o, "    pub {n}: {t},");
            }
            let _ = writeln!(o, "}}");
            // The layout as Goose has it, or no build.
            let _ = writeln!(o, "const _: () = assert!(::core::mem::size_of::<{name}>() == {});", s.size);
            for (n, _, off) in &fs {
                let _ = writeln!(o, "const _: () = assert!(::core::mem::offset_of!({name}, {n}) == {off});");
            }
            o.push('\n');
        }
        for e in &iface.enums {
            let name = self.tname(&e.qname);
            let tag_ty = match e.tag_size {
                1 => "u8",
                2 => "u16",
                4 => "u32",
                _ => "u64",
            };
            let payload = e.size - e.tag_size;
            for l in doc_lines(&e.doc) {
                let _ = writeln!(o, "/// {l}");
            }
            let _ = writeln!(o, "/// Goose's enum `{}`: its tag (variant index) and payload bytes.", e.qname);
            if e.align > 1 {
                let _ = writeln!(o, "#[repr(C, align({}))]", e.align);
            } else {
                let _ = writeln!(o, "#[repr(C, packed)]");
            }
            let _ = writeln!(o, "#[derive(Clone, Copy, Debug, PartialEq)]");
            let _ = writeln!(o, "pub struct {name} {{\n    pub tag: {tag_ty},\n    pub payload: [u8; {payload}],\n}}");
            let _ = writeln!(o, "impl {name} {{");
            for v in &e.variants {
                let c = snake(&v.name).to_uppercase();
                let _ = writeln!(o, "    pub const {c}: {tag_ty} = {};", v.tag);
            }
            let _ = writeln!(o, "    /// The variant's name.");
            let _ = writeln!(o, "    pub fn variant(&self) -> &'static str {{\n        match {{ self.tag }} {{");
            for v in &e.variants {
                let _ = writeln!(o, "            {} => \"{}\",", v.tag, v.name);
            }
            let _ = writeln!(o, "            _ => \"?\",\n        }}\n    }}\n}}");
            let _ = writeln!(o, "const _: () = assert!(::core::mem::size_of::<{name}>() == {});\n", e.size);
        }

        // The C declarations and the safe wrappers.
        let mut ffi = String::new();
        let mut wrappers = String::new();
        for x in &iface.exports {
            self.export(x, &mut ffi, &mut wrappers).map_err(|e| format!("export fn {}: {e}", x.qname))?;
        }
        let _ = writeln!(o, "/// The C functions, as the generated C defines them.");
        let _ = writeln!(o, "pub mod ffi {{\n    #[allow(unused_imports)]\n    use super::*;\n    extern \"C\" {{");
        let _ = writeln!(o, "        pub fn goose_init(argc: ::core::ffi::c_int, argv: *mut *mut ::core::ffi::c_char);");
        o.push_str(&ffi);
        let _ = writeln!(o, "    }}\n}}\n");
        let _ = writeln!(
            o,
            "::goose::__private::inventory::submit! {{ ::goose::GooseInit {{ program: {:?}, init: ffi::goose_init }} }}\n",
            self.program
        );
        o.push_str(&wrappers);
        self.out = o;
        Ok(())
    }

    fn export(&self, x: &Export, ffi: &mut String, w: &mut String) -> Result<(), String> {
        let fname = ident(&snake(&x.name));
        let mut cparams: Vec<String> = Vec::new();
        let mut rparams: Vec<String> = Vec::new();
        let mut args: Vec<String> = Vec::new();
        let mut pre: Vec<String> = Vec::new();
        let mut post: Vec<(String, String)> = Vec::new(); // (type, expression) results after the first
        let mut builder = false;
        let mut borrowed_params = false;
        for (i, p) in x.params.iter().enumerate() {
            let n = ident(&p.name);
            match &p.ty {
                GTy::Prim(t) if t == "bool" => {
                    cparams.push(format!("{n}: u8"));
                    rparams.push(format!("{n}: bool"));
                    args.push(format!("{n} as u8"));
                }
                GTy::Prim(t) => {
                    cparams.push(format!("{n}: {t}"));
                    rparams.push(format!("{n}: {t}"));
                    args.push(n.clone());
                }
                GTy::Struct(_) | GTy::Enum(_) => {
                    let t = self.cty(&p.ty)?;
                    cparams.push(format!("{n}: {t}"));
                    rparams.push(format!("{n}: {t}"));
                    args.push(n.clone());
                }
                GTy::Ref { to, constant } => {
                    let t = self.rty(to)?;
                    let ct = if matches!(&**to, GTy::Prim(p) if p == "bool") { "u8".to_string() } else { t.clone() };
                    borrowed_params = true;
                    if *constant {
                        cparams.push(format!("{n}: *const {ct}"));
                        rparams.push(format!("{n}: &'a {t}"));
                        args.push(format!("{n} as *const {t} as *const {ct}"));
                    } else {
                        cparams.push(format!("{n}: *mut {ct}"));
                        rparams.push(format!("{n}: &'a mut {t}"));
                        args.push(format!("{n} as *mut {t} as *mut {ct}"));
                    }
                }
                GTy::Slice { elem, constant } => {
                    let t = self.rty(elem)?;
                    borrowed_params = true;
                    cparams.push(format!("{n}: GooseSlice<{t}>"));
                    if *constant {
                        rparams.push(format!("{n}: &'a [{t}]"));
                        args.push(format!("GooseSlice::from_slice({n})"));
                    } else {
                        rparams.push(format!("{n}: &'a mut [{t}]"));
                        args.push(format!("GooseSlice::from_mut_slice({n})"));
                    }
                }
                GTy::Builder { elem } => {
                    // The runtime's scratch builder (goose-patches/0001).
                    builder = true;
                    let t = if matches!(&**elem, GTy::Prim(p) if p == "u8") { "u8".to_string() } else { self.rty(elem)? };
                    let d = format!("__b{i}");
                    let l = format!("__b{i}_len");
                    cparams.push(format!("{n}_data: *mut *const {t}, {n}_len: *mut i64"));
                    pre.push(format!("let mut {d}: *const {t} = ::core::ptr::null();"));
                    pre.push(format!("let mut {l}: i64 = 0;"));
                    args.push(format!("&mut {d}, &mut {l}"));
                    post.push((format!("&'a [{t}]"), format!("unsafe {{ __slice({d}, {l}) }}")));
                }
                other => return Err(format!("parameter {} of type {other:?} cannot cross to Rust", p.name)),
            }
        }
        // Results: the first as C's return, the rest through out-pointers.
        let mut ret_c = String::new();
        let mut first: Option<(String, String)> = None; // (rust type, expression of __r)
        let mut outs: Vec<(String, String)> = Vec::new();
        for (k, r) in x.results.iter().enumerate() {
            match (&r.ty, k) {
                (GTy::Slice { elem, .. }, 0) if matches!(&**elem, GTy::Prim(p) if p == "u8") => {
                    ret_c = " -> *const u8".into();
                    cparams.push("out_len: *mut i64".into());
                    pre.push("let mut __len: i64 = 0;".into());
                    args.push("&mut __len".into());
                    first = Some(("&'a [u8]".into(), "unsafe { __slice(__r, __len) }".into()));
                }
                (GTy::Prim(p), 0) if p == "bool" => {
                    ret_c = " -> u8".into();
                    first = Some(("bool".into(), "__r != 0".into()));
                }
                (t, 0) => {
                    let ct = self.cty(t)?;
                    ret_c = format!(" -> {ct}");
                    first = Some((self.rty(t)?, "__r".into()));
                }
                (GTy::Slice { elem, .. }, _) if matches!(&**elem, GTy::Prim(p) if p == "u8") => {
                    let d = format!("__o{k}");
                    let l = format!("__o{k}_len");
                    cparams.push(format!("out{k}: *mut *const u8, out{k}_len: *mut i64"));
                    pre.push(format!("let mut {d}: *const u8 = ::core::ptr::null();"));
                    pre.push(format!("let mut {l}: i64 = 0;"));
                    args.push(format!("&mut {d}, &mut {l}"));
                    outs.push(("&'a [u8]".into(), format!("unsafe {{ __slice({d}, {l}) }}")));
                }
                (t, _) => {
                    let ct = self.cty(t)?;
                    let d = format!("__o{k}");
                    cparams.push(format!("out{k}: *mut {ct}"));
                    pre.push(format!("let mut {d}: {ct} = unsafe {{ ::core::mem::zeroed() }};"));
                    args.push(format!("&mut {d}"));
                    if matches!(t, GTy::Prim(p) if p == "bool") {
                        outs.push(("bool".into(), format!("{d} != 0")));
                    } else {
                        outs.push((self.rty(t)?, d.clone()));
                    }
                }
            }
        }
        let _ = writeln!(ffi, "        pub fn {}({}){ret_c};", ident(&x.symbol), cparams.join(", "));

        let mut types = Vec::new();
        let mut exprs = Vec::new();
        if let Some((t, e)) = &first {
            types.push(t.clone());
            exprs.push(e.clone());
        }
        for (t, e) in outs.iter().chain(post.iter()) {
            types.push(t.clone());
            exprs.push(e.clone());
        }
        let ret_ty = match types.len() {
            0 => String::new(),
            1 => format!(" -> {}", types[0]),
            _ => format!(" -> ({})", types.join(", ")),
        };
        let ret_expr = match exprs.len() {
            0 => String::new(),
            1 => exprs[0].clone(),
            _ => format!("({})", exprs.join(", ")),
        };
        let lifetime = types.iter().any(|t| t.contains("'a")) || borrowed_params;
        let rt = if builder { "rt: &'a mut Runtime" } else { "rt: &'a Runtime" };
        let generics = if lifetime || builder { "<'a>" } else { "<'a>" };
        for l in doc_lines(&x.doc) {
            let _ = writeln!(w, "/// {l}");
        }
        if builder {
            let _ = writeln!(w, "///\n/// What the builders hold lives in the runtime's scratch builders until the next\n/// exported call, which needs the runtime mutably again.");
        }
        let mut params = vec![rt.to_string()];
        params.extend(rparams);
        let _ = writeln!(w, "#[allow(unused_mut, unused_unsafe, clippy::all)]");
        let _ = writeln!(w, "pub fn {fname}{generics}({}){ret_ty} {{", params.join(", "));
        let _ = writeln!(w, "    let _ = rt;");
        for p in &pre {
            let _ = writeln!(w, "    {p}");
        }
        let call = format!("unsafe {{ ffi::{}({}) }}", ident(&x.symbol), args.join(", "));
        if first.is_some() {
            let _ = writeln!(w, "    let __r = {call};");
        } else {
            let _ = writeln!(w, "    {call};");
        }
        if !ret_expr.is_empty() {
            let _ = writeln!(w, "    {ret_expr}");
        }
        let _ = writeln!(w, "}}\n");
        Ok(())
    }
}

/// The helper every slice result goes through, written once into the module.
pub const PRELUDE: &str = r#"
/// A slice the Goose program hands back: empty for a null pointer.
#[allow(dead_code)]
unsafe fn __slice<'a, T>(p: *const T, n: i64) -> &'a [T] {
    if p.is_null() || n <= 0 {
        &[]
    } else {
        ::core::slice::from_raw_parts(p, n as usize)
    }
}
"#;
